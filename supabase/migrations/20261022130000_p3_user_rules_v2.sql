-- Phase 3: user merchant / person rules v2 (NOT RUN; apply manually after
-- migration-checks/20261022130000_p3_user_rules_v2/precheck.sql).
--
-- Additive only. Existing rows keep every value; new columns get safe
-- defaults. The rule's own category / purpose columns stay the separate
-- category and purpose overrides (no duplicate columns). The app pushes
-- without these columns until this has run, and keeps its own values.

begin;

alter table public.user_merchants
  add column if not exists is_family boolean not null default false,
  add column if not exists kind text not null default 'merchant',
  add column if not exists revision integer not null default 1,
  add column if not exists upi_id_normalized text;

do $$
begin
  if not exists (select 1 from pg_constraint
                  where conname = 'user_merchants_kind_check'
                    and conrelid = 'public.user_merchants'::regclass) then
    alter table public.user_merchants
      add constraint user_merchants_kind_check
      check (kind in ('merchant', 'person'));
  end if;
end $$;

create index if not exists user_merchants_user_upi_idx
  on public.user_merchants (user_id, upi_id_normalized)
  where upi_id_normalized is not null;

-- History of every change to a user's rule (owner-only, append-only).
-- Hard deletes are not logged: an account deletion cascades through
-- user_merchants and must never be blocked by a history insert. A soft
-- delete (deleted_at set) is logged as an update.
create table if not exists public.user_merchant_revisions (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  merchant_id uuid not null,
  normalized_payee text not null,
  revision integer not null,
  title text,
  category text,
  purpose text,
  is_family boolean,
  kind text,
  is_trusted boolean,
  deleted boolean not null default false,
  changed_at timestamptz not null default now()
);

create index if not exists user_merchant_revisions_user_idx
  on public.user_merchant_revisions (user_id, merchant_id, changed_at desc);

alter table public.user_merchant_revisions enable row level security;

drop policy if exists user_merchant_revisions_select_own on public.user_merchant_revisions;
create policy user_merchant_revisions_select_own
  on public.user_merchant_revisions for select to authenticated
  using ((select auth.uid()) = user_id);
-- No insert / update / delete policy: only the trigger below writes.

create or replace function public.user_merchants_log_revision()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
begin
  if tg_op = 'UPDATE' and
     (new.title, new.category, new.purpose, new.is_family, new.kind,
      new.is_trusted, new.deleted_at)
     is not distinct from
     (old.title, old.category, old.purpose, old.is_family, old.kind,
      old.is_trusted, old.deleted_at) then
    return new;
  end if;
  insert into public.user_merchant_revisions
    (user_id, merchant_id, normalized_payee, revision, title, category,
     purpose, is_family, kind, is_trusted, deleted)
  values
    (new.user_id, new.id, new.normalized_payee, new.revision, new.title,
     new.category, new.purpose, new.is_family, new.kind, new.is_trusted,
     new.deleted_at is not null);
  return new;
end;
$$;

revoke all on function public.user_merchants_log_revision() from public, anon, authenticated;

drop trigger if exists user_merchants_log_revision on public.user_merchants;
create trigger user_merchants_log_revision
  after insert or update on public.user_merchants
  for each row execute function public.user_merchants_log_revision();

grant select on public.user_merchant_revisions to authenticated;

commit;
